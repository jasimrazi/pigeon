#!/usr/bin/env node
/**
 * Cloudflare Resource Provisioning for Pigeon
 * Provisions D1, KV, R2 and Queues resources via Wrangler CLI,
 * and writes the provisioned IDs into git-ignored local wrangler config.
 */

import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const workerDir = path.resolve(rootDir, 'apps/worker');
const localTomlPath = path.resolve(workerDir, 'wrangler.toml.local');

function getArg(name, def = null) {
  const idx = process.argv.indexOf(name);
  if (idx !== -1 && idx + 1 < process.argv.length) {
    return process.argv[idx + 1];
  }
  return def;
}

const envName = getArg('--env', 'prod');
const isDryRun = process.argv.includes('--dry-run');

console.log(`\n=== Pigeon Cloudflare Provisioning (Environment: ${envName}) ===\n`);

function runWrangler(cmd, ignoreErrors = true) {
  try {
    const fullCmd = `npx wrangler ${cmd}`;
    console.log(`> ${fullCmd}`);
    const out = execSync(fullCmd, {
      cwd: workerDir,
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    return { ok: true, output: out };
  } catch (err) {
    if (!ignoreErrors) throw err;
    const stderr = err.stderr ? String(err.stderr) : '';
    const stdout = err.stdout ? String(err.stdout) : '';
    return { ok: false, output: `${stdout}\n${stderr}`, error: err };
  }
}

async function provision() {
  const d1Name = envName === 'dev' ? 'pigeon-db' : `pigeon-db-${envName}`;
  const kvName = envName === 'dev' ? 'pigeon-config' : `pigeon-config-${envName}`;
  const r2Name = envName === 'dev' ? 'pigeon-resumes' : `pigeon-resumes-${envName}`;
  const queueName = envName === 'dev' ? 'pigeon-jobs' : `pigeon-jobs-${envName}`;

  if (isDryRun) {
    console.log('[dry-run] Would create:');
    console.log(`  - D1 database: ${d1Name}`);
    console.log(`  - KV namespace: ${kvName}`);
    console.log(`  - R2 bucket: ${r2Name}`);
    console.log(`  - Queue: ${queueName}`);
    return;
  }

  // 1. Provision D1 Database
  console.log(`\n[1/4] Provisioning D1 Database (${d1Name})...`);
  let databaseId = null;
  const d1Res = runWrangler(`d1 create ${d1Name}`);
  const d1Match =
    d1Res.output.match(/database_id\s*=\s*"([^"]+)"/i) ||
    d1Res.output.match(/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/i);
  if (d1Match) {
    databaseId = d1Match[1];
    console.log(`  [ok] D1 database ready. ID: ${databaseId}`);
  } else if (d1Res.output.includes('already exists')) {
    console.log(`  [info] D1 database ${d1Name} already exists. Querying list...`);
    const listRes = runWrangler('d1 list --json');
    try {
      const list = JSON.parse(listRes.output);
      const found = list.find((db) => db.name === d1Name);
      if (found) databaseId = found.uuid;
    } catch {
      // Ignore
    }
  }

  // 2. Provision KV Namespace
  console.log(`\n[2/4] Provisioning KV Namespace (${kvName})...`);
  let kvId = null;
  const kvRes = runWrangler(`kv namespace create ${kvName}`);
  const kvMatch = kvRes.output.match(/id\s*=\s*"([^"]+)"/i);
  if (kvMatch) {
    kvId = kvMatch[1];
    console.log(`  [ok] KV namespace ready. ID: ${kvId}`);
  } else if (kvRes.output.includes('already exists')) {
    console.log(`  [info] KV namespace ${kvName} already exists. Querying list...`);
    const listRes = runWrangler('kv namespace list');
    try {
      const list = JSON.parse(listRes.output);
      const found = list.find((ns) => ns.title === kvName || ns.title?.endsWith(kvName));
      if (found) kvId = found.id;
    } catch {
      // Ignore
    }
  }

  // 3. Provision R2 Bucket
  console.log(`\n[3/4] Provisioning R2 Bucket (${r2Name})...`);
  const r2Res = runWrangler(`r2 bucket create ${r2Name}`);
  if (r2Res.ok || r2Res.output.includes('already exists')) {
    console.log(`  [ok] R2 bucket ${r2Name} ready.`);
  } else {
    console.log(`  [notice] R2 response: ${r2Res.output.trim()}`);
  }

  // 4. Provision Queues
  console.log(`\n[4/4] Provisioning Queue (${queueName})...`);
  const qRes = runWrangler(`queues create ${queueName}`);
  if (qRes.ok || qRes.output.includes('already exists')) {
    console.log(`  [ok] Queue ${queueName} ready.`);
  } else {
    console.log(`  [notice] Queues response: ${qRes.output.trim()}`);
  }

  // 5. Write local wrangler override config
  console.log('\nWriting git-ignored local wrangler config...');
  const localTomlContent = `# Local Cloudflare Resource Overrides for Pigeon
# Generated by pnpm setup:cloudflare on ${new Date().toISOString()}
# GIT-IGNORED: Do not commit.

[env.${envName}]
name = "pigeon-worker-${envName}"

[[env.${envName}.d1_databases]]
binding = "DB"
database_name = "${d1Name}"
database_id = "${databaseId || 'YOUR_D1_DATABASE_ID'}"

[[env.${envName}.kv_namespaces]]
binding = "CONFIG"
id = "${kvId || 'YOUR_KV_NAMESPACE_ID'}"

[[env.${envName}.r2_buckets]]
binding = "RESUMES"
bucket_name = "${r2Name}"

[[env.${envName}.queues.producers]]
binding = "JOBS_QUEUE"
queue = "${queueName}"

[[env.${envName}.queues.consumers]]
queue = "${queueName}"
max_batch_size = 10
max_batch_timeout = 5
`;

  fs.writeFileSync(localTomlPath, localTomlContent, 'utf8');
  console.log(`  [ok] Saved configuration to ${path.relative(rootDir, localTomlPath)}`);

  console.log('\n=== Cloudflare Provisioning Complete ===');
  console.log('Next steps:');
  console.log(
    '  1. Run `pnpm setup:secrets --env ' +
      envName +
      '` to configure master key and bootstrap values.',
  );
  console.log('  2. Run `pnpm check:config` to verify setup readiness.');
  console.log(
    `  3. Apply database migrations: pnpm --filter @pigeon/worker wrangler d1 migrations apply ${d1Name} --remote\n`,
  );
}

provision().catch((err) => {
  console.error('[error] Provisioning failed:', err);
  process.exit(1);
});
